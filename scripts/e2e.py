"""End-to-end smoke test of the golden workflow: harness -> new agent -> agent checks -> cleanup.

Stdlib only, so it runs on Windows, macOS and Linux with any Python 3.11+. The thin wrappers
(`Makefile`, `scripts/e2e.ps1`, `scripts/e2e.sh`) just call this file.

    python scripts/e2e.py                 # full run
    python scripts/e2e.py --keep          # leave the generated agent in .e2e-work/ for inspection
    python scripts/e2e.py --live-evals    # needs approved cloud credentials and HARNESS_EVAL_REGION
    python scripts/e2e.py --from-stage 5  # skip harness stages 1-4 (reuses an existing .venv)

Exit code is 0 only if every stage passed. The report is written and the agent folder removed
even when a stage fails (unless --keep).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from dataclasses import asdict, dataclass, field
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORK = ROOT / ".e2e-work"
REPORT_DIR = ROOT / "e2e-report"
AGENT_NAME = "e2e-placeholder-agent"
AGENT_DIR = WORK / AGENT_NAME
SPEC_PATH = WORK / "spec.yaml"
VENV = ROOT / ".venv"
IS_WIN = os.name == "nt"
VENV_BIN = VENV / ("Scripts" if IS_WIN else "bin")
VENV_PY = VENV_BIN / ("python.exe" if IS_WIN else "python")

PLACEHOLDER_SPEC = f"""\
name: {AGENT_NAME}
division: e2e-test
owner: e2e.owner
sponsor: e2e.sponsor
classification: internal
description: Placeholder agent generated by scripts/e2e.py; safe to delete
location: australia-southeast2
environments: [nonprod]
egress_hosts:
  - api.example.com.au
"""


@dataclass
class Stage:
    n: int
    name: str
    status: str = "skipped"  # passed | failed | skipped
    seconds: float = 0.0
    detail: str = ""
    commands: list[str] = field(default_factory=list)


class StageFailed(Exception):
    pass


stages: list[Stage] = []


def say(msg: str) -> None:
    print(msg, flush=True)


def run(
    stage: Stage,
    cmd: list[str],
    *,
    cwd: Path = ROOT,
    env: dict[str, str] | None = None,
    check: bool = True,
) -> subprocess.CompletedProcess[str]:
    """Run a command, stream its output, record it on the stage."""
    shown = " ".join(str(c) for c in cmd)
    stage.commands.append(
        f"({cwd.relative_to(ROOT) if cwd != ROOT and cwd.is_relative_to(ROOT) else cwd}) {shown}"
    )
    say(f"    $ {shown}")
    try:
        proc = subprocess.run(
            cmd,
            check=False,
            cwd=cwd,
            env=env,
            text=True,
            encoding="utf-8",
            errors="replace",
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
    except FileNotFoundError as e:
        raise StageFailed(f"command not found: {cmd[0]} ({e})") from e
    for line in proc.stdout.splitlines()[-40:]:
        say(f"      {line}")
    if check and proc.returncode != 0:
        raise StageFailed(f"exit {proc.returncode}: {shown}")
    return proc


def clean_env() -> dict[str, str]:
    """Environment with the harness venv 'deactivated' (what `deactivate` effectively does)."""
    env = dict(os.environ)
    env.pop("VIRTUAL_ENV", None)
    env.pop("PYTHONHOME", None)
    venv_bin = os.path.normcase(str(VENV_BIN))
    parts = [p for p in env.get("PATH", "").split(os.pathsep) if os.path.normcase(p) != venv_bin]
    env["PATH"] = os.pathsep.join(parts)
    env["PYTHONUTF8"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"
    return env


def venv_env() -> dict[str, str]:
    """Environment with the harness venv 'activated'."""
    env = clean_env()
    env["VIRTUAL_ENV"] = str(VENV)
    env["PATH"] = str(VENV_BIN) + os.pathsep + env["PATH"]
    return env


def agents_cli() -> list[str]:
    if shutil.which("agents-cli"):
        return ["agents-cli"]
    if shutil.which("uvx"):
        return ["uvx", "--python", "3.13", "--from", "google-agents-cli", "agents-cli"]
    raise StageFailed("agents-cli not found; see README Prerequisites (uv tool install google-agents-cli)")


# --------------------------------------------------------------------------- stages


def s1_venv(st: Stage) -> None:
    if not VENV_PY.exists():
        if shutil.which("uv"):
            run(st, ["uv", "venv", "--python", "3.13", str(VENV)])
        else:
            run(st, [sys.executable, "-m", "venv", str(VENV)])
    run(st, [str(VENV_PY), "--version"], env=venv_env())
    st.detail = f"venv at {VENV.name}/ (activated via VIRTUAL_ENV + PATH)"


def s2_install(st: Stage) -> None:
    if shutil.which("uv"):
        run(st, ["uv", "pip", "install", "--python", str(VENV_PY), "-e", ".[dev]"], env=venv_env())
    else:
        run(st, [str(VENV_PY), "-m", "pip", "install", "-q", "-e", ".[dev]"], env=venv_env())
    run(st, [str(VENV_BIN / ("agentic-bootstrap.exe" if IS_WIN else "agentic-bootstrap")), "--help"], env=venv_env())
    st.detail = "harness installed with [dev]; agentic-bootstrap on venv PATH"


def s3_tests(st: Stage) -> None:
    run(st, [str(VENV_PY), "-m", "ruff", "check", "."], env=venv_env())
    p = run(st, [str(VENV_PY), "-m", "pytest", "-q"], env=venv_env())
    st.detail = "ruff clean; " + (p.stdout.strip().splitlines() or [""])[-1]


def s4_evals(st: Stage) -> None:
    out = REPORT_DIR / "harness-eval-report.json"
    REPORT_DIR.mkdir(exist_ok=True)
    run(st, [str(VENV_PY), "evals/run_evals.py", "--mode", "dry-run", "--out", str(out)], env=venv_env())
    if not out.exists():
        raise StageFailed(f"eval report not written: {out}")
    st.detail = f"dry-run evals green; report at {out.relative_to(ROOT)}"


def _bootstrap(*args: str) -> list[str]:
    return [str(VENV_BIN / ("agentic-bootstrap.exe" if IS_WIN else "agentic-bootstrap")), *args]


def s5_plan(st: Stage) -> None:
    WORK.mkdir(exist_ok=True)
    SPEC_PATH.write_text(PLACEHOLDER_SPEC, encoding="utf-8")
    p = run(st, _bootstrap("plan", str(SPEC_PATH)), env=venv_env())
    # stdout is the JSON plan (stderr is merged, but a successful plan prints nothing to stderr)
    try:
        plan = json.loads(p.stdout)
    except json.JSONDecodeError as e:
        raise StageFailed(f"plan output is not valid JSON: {e}") from e
    if not isinstance(plan, list) or not plan:
        raise StageFailed("plan is empty; expected at least one workload PR")
    st.detail = f"{len(plan)} PR(s) planned for placeholder spec"


def s6_new(st: Stage) -> None:
    if AGENT_DIR.exists():
        shutil.rmtree(AGENT_DIR)
    run(st, _bootstrap("new", str(SPEC_PATH), str(AGENT_DIR)), env=venv_env())
    for expected in ("AGENTS.md", "pyproject.toml", "agent", "evals", "tests"):
        if not (AGENT_DIR / expected).exists():
            raise StageFailed(f"generated agent is missing {expected}")
    leftovers = [
        f.name
        for f in AGENT_DIR.rglob("*")
        if f.is_file()
        and f.suffix in {".md", ".yaml", ".toml", ".py"}
        and "__AGENT_NAME__" in f.read_text(encoding="utf-8", errors="ignore")
    ]
    if leftovers:
        raise StageFailed(f"unrendered template placeholders in: {', '.join(leftovers)}")
    st.detail = f"agent rendered to {AGENT_DIR.relative_to(ROOT)}"


def s7_check(st: Stage) -> None:
    # TODO: enhance checks (add more than the security harness as the policy grows).
    run(st, _bootstrap("check", str(AGENT_DIR)), env=venv_env())
    st.detail = "security harness: no findings"


def s8_leave_venv(st: Stage) -> None:
    env = clean_env()
    probe = run(
        st, [sys.executable, "-c", "import os;print(os.environ.get('VIRTUAL_ENV'))"], cwd=AGENT_DIR, env=env
    )
    if probe.stdout.strip() != "None":
        raise StageFailed("VIRTUAL_ENV still set after deactivation")
    st.detail = "harness venv deactivated; working directory is the new agent"


def s9_init(st: Stage) -> None:
    env, cli = clean_env(), agents_cli()
    run(st, [*cli, "install"], cwd=AGENT_DIR, env=env)
    run(st, [*cli, "lint"], cwd=AGENT_DIR, env=env)
    run(st, ["uv", "run", "pytest", "-q"], cwd=AGENT_DIR, env=env)
    st.detail = "agents-cli install, lint and pytest passed in the agent"


def s10_commands(st: Stage, live_evals: bool) -> None:
    env, cli = clean_env(), agents_cli()
    run(st, [*cli, "--version"], cwd=AGENT_DIR, env=env)
    run(st, [*cli, "info"], cwd=AGENT_DIR, env=env)
    # Every `agents-cli ...` command the agent's AGENTS.md tells Copilot to use must exist.
    agents_md = (AGENT_DIR / "AGENTS.md").read_text(encoding="utf-8")
    cmds = sorted({m for m in re.findall(r"`agents-cli ([a-z][a-z -]*?)`", agents_md)})
    if not cmds:
        raise StageFailed("no agents-cli commands found in AGENTS.md")
    for c in cmds:
        run(st, [*cli, *c.split(), "--help"], cwd=AGENT_DIR, env=env)
    detail = f"agents-cli responds; AGENTS.md commands exist: {', '.join(cmds)}"
    if live_evals:
        eval_region = env.get("HARNESS_EVAL_REGION", "")
        model_region = env.get("GOOGLE_CLOUD_LOCATION", "")
        run(
            st,
            [
                str(VENV_PY),
                "-c",
                (
                    "import sys; from harness.residency import assert_allowed; "
                    "assert_allowed(sys.argv[1]); assert_allowed(sys.argv[2])"
                ),
                model_region,
                eval_region,
            ],
            env=env,
        )
        run(
            st,
            [
                *cli,
                "eval",
                "run",
                "--region",
                eval_region,
                "--dataset",
                str(Path("tests", "eval", "datasets", "basic-dataset.json")),
                "--config",
                str(Path("tests", "eval", "eval_config.yaml")),
            ],
            cwd=AGENT_DIR,
            env=env,
        )
        detail += "; live `eval run` passed"
    else:
        detail += "; live `eval run` skipped (use --live-evals)"
    st.detail = detail


def s11_final(st: Stage) -> None:
    env, cli = clean_env(), agents_cli()
    run(st, [*cli, "lint"], cwd=AGENT_DIR, env=env)
    run(st, ["uv", "run", "pytest", "-q"], cwd=AGENT_DIR, env=env)
    run(st, _bootstrap("check", str(AGENT_DIR)), env=venv_env())  # scanner, harness-side
    st.detail = "lint, tests and security scan all green"


# --------------------------------------------------------------------------- report


def write_report(started: str, ok: bool, kept: bool) -> Path:
    REPORT_DIR.mkdir(exist_ok=True)
    (REPORT_DIR / "e2e-report.json").write_text(
        json.dumps({"started": started, "ok": ok, "stages": [asdict(s) for s in stages]}, indent=2),
        encoding="utf-8",
    )
    icon = {"passed": "PASS", "failed": "FAIL", "skipped": "SKIP"}
    lines = [
        "# End-to-end test summary",
        "",
        f"- Started: {started}",
        f"- Result: **{'PASSED' if ok else 'FAILED'}**",
        f"- Agent folder: {'kept at ' + str(AGENT_DIR.relative_to(ROOT)) if kept else 'deleted'}",
        "",
        "| # | Stage | Result | Time | Detail |",
        "| --- | --- | --- | --- | --- |",
    ]
    for s in stages:
        detail = s.detail.replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {s.n} | {s.name} | {icon[s.status]} | {s.seconds:.1f}s | {detail} |")
    lines += ["", "## Commands", ""]
    for s in stages:
        if s.commands:
            lines += [f"### {s.n}. {s.name}", "", *[f"- `{c}`" for c in s.commands], ""]
    path = REPORT_DIR / "e2e-report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def s13_cleanup(st: Stage, keep: bool) -> None:
    if keep:
        st.status, st.detail = "skipped", "--keep: agent folder left in place"
        return
    # Only ever delete the folder this script owns.
    if WORK.exists() and WORK.resolve() == (ROOT / ".e2e-work").resolve():
        shutil.rmtree(WORK, ignore_errors=False)
    st.detail = "removed .e2e-work/ (spec and generated agent)"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--keep", action="store_true", help="do not delete the generated agent")
    ap.add_argument(
        "--live-evals",
        action="store_true",
        help="run live evals (needs approved credentials, GOOGLE_CLOUD_LOCATION and HARNESS_EVAL_REGION)",
    )
    ap.add_argument("--from-stage", type=int, default=1, help="start at this stage (reuses .venv)")
    a = ap.parse_args()

    started = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
    plan = [
        (1, "Activate venv", s1_venv),
        (2, "Install harness dependencies", s2_install),
        (3, "Lint and run harness tests", s3_tests),
        (4, "Run harness evals", s4_evals),
        (5, "Plan agent from placeholder spec", s5_plan),
        (6, "Bootstrap new agent", s6_new),
        (7, "Check new agent (security harness)", s7_check),
        (8, "Deactivate venv, enter agent", s8_leave_venv),
        (9, "Agent init: install, lint, test", s9_init),
        (10, "Validate agents-cli commands", lambda st: s10_commands(st, a.live_evals)),
        (11, "Final lint, test and scan", s11_final),
    ]
    stages.extend(Stage(n, name) for n, name, _ in plan)
    failed = False
    for st, (n, name, fn) in zip(stages, plan):
        if n < a.from_stage:
            st.detail = "skipped (--from-stage)"
            continue
        if failed:
            st.detail = "not run: earlier stage failed"
            continue
        say(f"\n[{n:>2}/13] {name}")
        t0 = time.monotonic()
        try:
            fn(st)
            st.status = "passed"
        except StageFailed as e:
            st.status, st.detail, failed = "failed", str(e), True
            say(f"    FAILED: {e}")
        except Exception as e:  # noqa: BLE001 - report any bug in a stage, then still clean up
            st.status, st.detail, failed = "failed", f"{type(e).__name__}: {e}", True
            say(f"    ERROR: {st.detail}")
        st.seconds = time.monotonic() - t0

    # 12 (report) must be written before 13 (delete) so the report can say what happened;
    # the report records stage 13 as the final line item.
    st12, st13 = Stage(12, "Write end-to-end report"), Stage(13, "Delete new agent folder")
    stages.extend([st12, st13])
    say("\n[12/13] Write end-to-end report")
    ok = not failed
    try:
        st13.status = "passed" if not a.keep else "skipped"
        st13.detail = (
            "removed .e2e-work/ (spec and generated agent)" if not a.keep else "--keep: left in place"
        )
        st12.status, st12.detail = "passed", "report written to e2e-report/"
        report = write_report(started, ok, a.keep)
    except OSError as e:
        say(f"    could not write report: {e}")
        ok, report = False, None
    say("\n[13/13] Delete new agent folder")
    try:
        s13_cleanup(Stage(13, ""), a.keep)
    except OSError as e:
        say(f"    cleanup failed: {e}")
        ok = False
        st13.status, st13.detail = "failed", str(e)
        write_report(started, ok, True)

    say(f"\nE2E {'PASSED' if ok else 'FAILED'}" + (f" - report: {report}" if report else ""))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
